//! Rule 19 (issues #2091, #2108): a test that exists only in the `e2e` build,
//! outside a `tests/e2e_*.rs` binary, sits in a module whose name starts with
//! [`MODULE_PREFIX`].
//!
//! ## What it is for
//!
//! Lane 1's shards (`scripts/e2e-shard.sh`, called by `ci.yml`'s `e2e` matrix
//! and `.rwx/ci.yml`'s `e2e` task) run the `--features e2e` nextest archive,
//! which holds every test binary in the workspace. The library and the non-e2e
//! integration tests in it already run in the fast tier (`cargo test-fast`, the
//! `test` job/task), so the shards select only
//!
//! - the `tests/e2e_*.rs` binaries, by binary name, and
//! - tests elsewhere in the root package whose path has a module named
//!   `e2e_only…`, by package and test name.
//!
//! The second half is the one a filter cannot derive: a `#[test]` under
//! `#[cfg(feature = "e2e")]` in `src/` compiles only into the e2e archive, so
//! the fast tier never sees it, and if the shard filter did not select it
//! either it would run in no CI job at all, with every gate green. This rule
//! turns that silent loss into a build failure: it finds every such test and
//! requires the module name the filter keys on.
//!
//! ## What it reads
//!
//! Every `.rs` file reachable through `mod` declarations from a crate root of
//! the root package — `src/lib.rs`, `src/main.rs` and each `tests/*.rs` other
//! than `tests/e2e_*.rs` — with the `cfg` and module names accumulated along
//! the way, `#[path]` included. A file reached only from `tests/e2e_*.rs` roots
//! is not read: the binary-name half of the filter already selects all of it.
//!
//! "Exists only in the `e2e` build" is decided per `cfg` predicate: one that
//! cannot hold with `feature = "e2e"` off, whatever the other atoms are
//! (`test` counts as on, since these are test binaries). `cfg(feature = "e2e")`,
//! `cfg(all(unix, feature = "e2e"))` and `cfg(all(test, feature = "e2e"))`
//! qualify; `cfg(any(test, feature = "e2e"))` and `cfg(not(feature = "e2e"))`
//! do not. A test is a `fn` carrying an attribute whose last path segment is
//! `test` (`#[test]`, `#[tokio::test]`, …).
//!
//! ## What it does NOT see, so it is not mistaken for coverage
//!
//! - a test whose BODY changes under the feature (`cfg!(feature = "e2e")`, or
//!   `cfg` arms inside the code it calls) but which exists in both builds:
//!   it runs once, in the fast tier, against the plain build. The e2e arms are
//!   test seams for the `tests/e2e_*.rs` binaries, which do run;
//! - tests generated by a macro other than a `test` attribute on a `fn`;
//! - crates other than the root package: only the root package has an `e2e`
//!   feature.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::rc::Rc;

/// The module-name prefix the shard filter selects on. `scripts/e2e-shard.sh`
/// holds the matching filter; [`run`] fails when the script stops naming it
/// ([`shard_filter_findings`]).
pub const MODULE_PREFIX: &str = "e2e_only";

/// Where the shard filter lives.
pub const SHARD_SCRIPT: &str = "scripts/e2e-shard.sh";

/// What one predicate can evaluate to with `feature = "e2e"` off.
#[derive(Clone, Copy)]
struct Can {
    yes: bool,
    no: bool,
}

const FREE: Can = Can {
    yes: true,
    no: true,
};

fn can(meta: &syn::Meta) -> Can {
    use syn::punctuated::Punctuated;
    use syn::{Meta, Token};
    match meta {
        Meta::Path(p) if p.is_ident("test") => Can {
            yes: true,
            no: false,
        },
        Meta::NameValue(nv) if nv.path.is_ident("feature") => {
            let is_e2e = matches!(
                &nv.value,
                syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. }) if s.value() == "e2e"
            );
            if is_e2e {
                Can {
                    yes: false,
                    no: true,
                }
            } else {
                FREE
            }
        }
        Meta::List(list) => {
            let Ok(terms) = list.parse_args_with(Punctuated::<Meta, Token![,]>::parse_terminated)
            else {
                return FREE;
            };
            let parts: Vec<Can> = terms.iter().map(can).collect();
            if list.path.is_ident("all") {
                Can {
                    yes: parts.iter().all(|c| c.yes),
                    no: parts.is_empty() || parts.iter().any(|c| c.no),
                }
            } else if list.path.is_ident("any") {
                Can {
                    yes: parts.iter().any(|c| c.yes),
                    no: parts.iter().all(|c| c.no),
                }
            } else if list.path.is_ident("not") && parts.len() == 1 {
                Can {
                    yes: parts[0].no,
                    no: parts[0].yes,
                }
            } else {
                FREE
            }
        }
        _ => FREE,
    }
}

/// Does any `#[cfg(..)]` / `#![cfg(..)]` in `attrs` require `feature = "e2e"`?
fn requires_e2e(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|attr| {
        if !attr.path().is_ident("cfg") {
            return false;
        }
        let syn::Meta::List(list) = &attr.meta else {
            return false;
        };
        list.parse_args::<syn::Meta>().is_ok_and(|m| !can(&m).yes)
    })
}

fn is_test_fn(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|attr| {
        attr.path()
            .segments
            .last()
            .is_some_and(|seg| seg.ident == "test")
    })
}

/// The context a file or item is reached in.
#[derive(Clone, Copy)]
struct Ctx {
    e2e: bool,
    selected: bool,
}

/// One crate's walk.
struct Walk<'a> {
    root: &'a Path,
    /// Every parsed file, keyed by canonical path. A `mod` target that is not
    /// in it yet (a `#[path]` outside `src/` and `tests/`) is parsed on demand.
    parsed: &'a mut BTreeMap<PathBuf, Rc<syn::File>>,
    visited: BTreeSet<PathBuf>,
    findings: BTreeSet<String>,
    tests_seen: usize,
}

impl Walk<'_> {
    fn file(&mut self, file: &Path, dir: &Path, ctx: Ctx) {
        // Keys are canonical, so `tests/../src/x.rs` and `src/x.rs` are one file.
        let file = canonical(file);
        // A file reached twice in one crate would be a compile error; across
        // crates (`tests/common` from many roots) it is reached once per root,
        // and the findings set dedups.
        if !self.visited.insert(file.clone()) {
            return;
        }
        let display = file
            .strip_prefix(self.root)
            .unwrap_or(&file)
            .to_string_lossy()
            .replace('\\', "/");
        let ast = match self.parsed.get(&file) {
            Some(ast) => Rc::clone(ast),
            None => match std::fs::read_to_string(&file)
                .ok()
                .and_then(|text| syn::parse_file(&text).ok())
            {
                Some(ast) => {
                    let ast = Rc::new(ast);
                    self.parsed.insert(file.clone(), Rc::clone(&ast));
                    ast
                }
                None => {
                    self.findings.insert(format!(
                        "{display}: a `mod` declaration loads it and it cannot be read or parsed \
                         — its tests were not checked, which is a failure, never a skip"
                    ));
                    return;
                }
            },
        };
        let ctx = Ctx {
            e2e: ctx.e2e || requires_e2e(&ast.attrs),
            ..ctx
        };
        self.items(&ast.items, &file, &display, dir, false, ctx);
    }

    fn items(
        &mut self,
        items: &[syn::Item],
        file: &Path,
        display: &str,
        dir: &Path,
        inline: bool,
        ctx: Ctx,
    ) {
        for item in items {
            match item {
                syn::Item::Fn(f) if is_test_fn(&f.attrs) => {
                    self.tests_seen += 1;
                    if (ctx.e2e || requires_e2e(&f.attrs)) && !ctx.selected {
                        self.findings.insert(format!(
                            "{display}:{}: `{}` exists only in the `e2e` build, outside a \
                             `tests/e2e_*.rs` binary and outside a module named `{MODULE_PREFIX}…`, \
                             so the fast tier never compiles it and the lane-1 shard filter \
                             (`{SHARD_SCRIPT}`) never selects it: it runs in no CI job. Move it \
                             into a `mod {MODULE_PREFIX} {{ … }}` (or a module whose name starts \
                             with `{MODULE_PREFIX}`), or drop the `cfg`.",
                            f.sig.ident.span().start().line,
                            f.sig.ident
                        ));
                    }
                }
                syn::Item::Mod(m) => {
                    let name = m.ident.to_string();
                    let child = Ctx {
                        e2e: ctx.e2e || requires_e2e(&m.attrs),
                        selected: ctx.selected || name.starts_with(MODULE_PREFIX),
                    };
                    match &m.content {
                        Some((_, inner)) => {
                            self.items(inner, file, display, &dir.join(&name), true, child);
                        }
                        None => {
                            if let Some(target) = resolve(m, file, dir, inline) {
                                let child_dir = module_dir(&target, false);
                                self.file(&target, &child_dir, child);
                            }
                        }
                    }
                }
                _ => {}
            }
        }
    }
}

/// The file a `mod name;` declaration loads.
fn resolve(m: &syn::ItemMod, file: &Path, dir: &Path, inline: bool) -> Option<PathBuf> {
    let explicit = m.attrs.iter().find_map(|attr| {
        if !attr.path().is_ident("path") {
            return None;
        }
        let syn::Meta::NameValue(nv) = &attr.meta else {
            return None;
        };
        let syn::Expr::Lit(syn::ExprLit {
            lit: syn::Lit::Str(s),
            ..
        }) = &nv.value
        else {
            return None;
        };
        Some(s.value())
    });
    let candidates = match explicit {
        // Relative to the declaring file's directory at a file's top level,
        // to the inline module's directory inside one.
        Some(p) => vec![if inline { dir } else { file.parent()? }.join(p)],
        None => {
            let name = m.ident.to_string();
            vec![
                dir.join(format!("{name}.rs")),
                dir.join(&name).join("mod.rs"),
            ]
        }
    };
    candidates
        .into_iter()
        .find(|c| c.is_file())
        .map(|c| canonical(&c))
}

/// `path` with `..`, `.` and symlinks resolved, or as given when it cannot be.
fn canonical(path: &Path) -> PathBuf {
    std::fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf())
}

/// The directory a file's `mod x;` declarations resolve against.
fn module_dir(file: &Path, crate_root: bool) -> PathBuf {
    let parent = file.parent().unwrap_or(Path::new("")).to_path_buf();
    if crate_root {
        return parent;
    }
    match file.file_name().and_then(|n| n.to_str()) {
        Some("mod.rs") => parent,
        _ => match file.file_stem() {
            Some(stem) => parent.join(stem),
            None => parent,
        },
    }
}

fn collect_rs(dir: &Path, out: &mut Vec<PathBuf>, errors: &mut Vec<String>) {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) => {
            errors.push(format!("{}: cannot be listed ({e})", dir.display()));
            return;
        }
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_rs(&path, out, errors);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
}

/// The root package's crate roots that do not build a `tests/e2e_*.rs` binary.
fn crate_roots(root: &Path) -> Vec<PathBuf> {
    let mut roots: Vec<PathBuf> = ["src/lib.rs", "src/main.rs"]
        .iter()
        .map(|r| root.join(r))
        .filter(|p| p.is_file())
        .collect();
    if let Ok(entries) = std::fs::read_dir(root.join("tests")) {
        let mut tests: Vec<PathBuf> = entries
            .flatten()
            .map(|e| e.path())
            .filter(|p| {
                p.is_file()
                    && p.extension().is_some_and(|e| e == "rs")
                    && !p
                        .file_name()
                        .and_then(|n| n.to_str())
                        .is_some_and(|n| n.starts_with("e2e_"))
            })
            .collect();
        tests.sort();
        roots.extend(tests);
    }
    roots
}

/// The two selectors the shard script must hold. A rename on one side alone
/// would let this rule pass tests the filter no longer selects, or select
/// nothing it should.
///
/// Read off the `lane1=` assignment and the line that passes it to nextest,
/// never off comments: a selector left only in a comment selects nothing.
fn shard_filter_findings(script: &str) -> Vec<String> {
    let code: Vec<&str> = script
        .lines()
        .map(str::trim)
        .filter(|l| !l.starts_with('#'))
        .collect();
    let Some(lane1) = code.iter().find(|l| l.starts_with("lane1=")) else {
        return vec![format!(
            "{SHARD_SCRIPT}: assigns no `lane1=` filter — this rule cannot tell what the \
             shards select"
        )];
    };
    let mut out = Vec::new();
    let module = format!("(package(dot-agent-deck) & test(/(^|::){MODULE_PREFIX}[a-z0-9_]*::/))");
    for needle in [module.as_str(), "binary(/^e2e_/)"] {
        if !lane1.contains(needle) {
            out.push(format!(
                "{SHARD_SCRIPT}: its `lane1=` filter no longer holds `{needle}` — the shards \
                 would stop running tests this rule counts as selected"
            ));
        }
    }
    if !code.iter().any(|l| l.contains("-E \"($lane1)")) {
        out.push(format!(
            "{SHARD_SCRIPT}: no line passes `-E \"($lane1)…\"` to nextest — the `lane1=` \
             filter this rule reads is not what the shards run"
        ));
    }
    out
}

/// Run the check against `root` (the repository root).
pub fn run(root: &Path) -> Vec<String> {
    // Canonical, so every path below — collected, resolved through `#[path]`
    // or a crate root — is keyed the same way.
    let root = &canonical(root);
    let mut out = match std::fs::read_to_string(root.join(SHARD_SCRIPT)) {
        Ok(text) => shard_filter_findings(&text),
        Err(e) => vec![format!(
            "{SHARD_SCRIPT}: cannot be read ({e}) — the shard filter this rule keeps in step \
             with `{MODULE_PREFIX}` moved; point the rule at it rather than deleting the rule"
        )],
    };
    let mut files = Vec::new();
    for dir in ["src", "tests"] {
        let path = root.join(dir);
        if !path.is_dir() {
            out.push(format!(
                "{dir}/ not found under {} — this rule scanned nothing",
                root.display()
            ));
            continue;
        }
        collect_rs(&path, &mut files, &mut out);
    }
    let mut parsed = BTreeMap::new();
    for file in files {
        let shown = file
            .strip_prefix(root)
            .unwrap_or(&file)
            .display()
            .to_string();
        let Ok(text) = std::fs::read_to_string(&file) else {
            out.push(format!("{shown}: could not be read as UTF-8"));
            continue;
        };
        match syn::parse_file(&text) {
            Ok(ast) => {
                parsed.insert(canonical(&file), Rc::new(ast));
            }
            Err(e) => out.push(format!(
                "{shown}: does not parse ({e}) — a file this rule cannot read is a failure, \
                 never a skip"
            )),
        }
    }
    let roots = crate_roots(root);
    if roots.is_empty() {
        out.push("no crate root (`src/lib.rs`, `src/main.rs`, `tests/*.rs`) found".into());
        return out;
    }
    let mut findings = BTreeSet::new();
    let mut tests_seen = 0usize;
    for crate_root in roots {
        let mut walk = Walk {
            root,
            parsed: &mut parsed,
            visited: BTreeSet::new(),
            findings: BTreeSet::new(),
            tests_seen: 0,
        };
        let dir = module_dir(&crate_root, true);
        walk.file(
            &crate_root,
            &dir,
            Ctx {
                e2e: false,
                selected: false,
            },
        );
        tests_seen += walk.tests_seen;
        findings.extend(walk.findings);
    }
    if tests_seen == 0 {
        out.push(
            "saw no test `fn` in any crate root's module tree — the walk is broken, and this \
             rule is matching nothing"
                .into(),
        );
    }
    out.extend(findings);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tree(files: &[(&str, &str)]) -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        // The rule reports a missing `src/` or `tests/` as a finding, so
        // every fixture has both.
        std::fs::create_dir_all(dir.path().join("src")).unwrap();
        std::fs::create_dir_all(dir.path().join("tests")).unwrap();
        for (path, body) in files {
            let path = dir.path().join(path);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, body).unwrap();
        }
        dir
    }

    const SCRIPT: &str = "lane1='binary(/^e2e_/) | (package(dot-agent-deck) & test(/(^|::)e2e_only[a-z0-9_]*::/))'\n\
        exec \"$@\" -E \"($lane1) & not $version\"\n";

    fn findings(files: &[(&str, &str)]) -> Vec<String> {
        let mut all = files.to_vec();
        all.push((SHARD_SCRIPT, SCRIPT));
        let dir = tree(&all);
        run(dir.path())
    }

    const PLAIN: &str = "#[test] fn plain() {}\n";

    #[test]
    fn an_e2e_gated_test_outside_the_module_is_reported() {
        let found = findings(&[(
            "src/lib.rs",
            "#[test] fn plain() {}\n#[cfg(feature = \"e2e\")]\n#[test]\nfn gated() {}\n",
        )]);
        assert_eq!(found.len(), 1, "{found:?}");
        assert!(found[0].starts_with("src/lib.rs:4: `gated`"), "{found:?}");
    }

    #[test]
    fn a_gated_test_in_the_module_passes() {
        let found = findings(&[(
            "src/lib.rs",
            "#[cfg(feature = \"e2e\")]\nmod e2e_only { #[tokio::test] async fn gated() {} }\n\
             #[cfg(all(test, feature = \"e2e\"))]\nmod e2e_only_standins { #[test] fn s() {} }\n",
        )]);
        assert!(found.is_empty(), "{found:?}");
    }

    #[test]
    fn predicates_that_hold_without_the_feature_are_not_gated() {
        let found = findings(&[(
            "src/lib.rs",
            "#[cfg(any(test, feature = \"e2e\"))] #[test] fn a() {}\n\
             #[cfg(not(feature = \"e2e\"))] #[test] fn b() {}\n\
             #[cfg(unix)] #[test] fn c() {}\n",
        )]);
        assert!(found.is_empty(), "{found:?}");
    }

    #[test]
    fn gating_is_inherited_through_inline_and_file_modules() {
        let found = findings(&[
            (
                "src/lib.rs",
                "#[cfg(all(unix, feature = \"e2e\"))] mod seams;\nmod inner { #[cfg(feature = \"e2e\")] mod deeper { #[test] fn t() {} } }\n",
            ),
            ("src/seams.rs", "mod sub;\n"),
            ("src/seams/sub.rs", PLAIN),
        ]);
        assert_eq!(found.len(), 2, "{found:?}");
        assert!(found.iter().any(|f| f.starts_with("src/lib.rs:2: `t`")));
        assert!(
            found
                .iter()
                .any(|f| f.starts_with("src/seams/sub.rs:1: `plain`"))
        );
    }

    #[test]
    fn a_file_opening_with_the_gate_is_gated() {
        let found = findings(&[
            ("src/lib.rs", "mod gated;\n"),
            (
                "src/gated.rs",
                "#![cfg(feature = \"e2e\")]\n#[test] fn t() {}\n",
            ),
        ]);
        assert_eq!(found.len(), 1, "{found:?}");
    }

    #[test]
    fn e2e_binaries_are_not_read_and_other_integration_tests_are() {
        let found = findings(&[
            ("src/lib.rs", PLAIN),
            (
                "tests/e2e_thing.rs",
                "#![cfg(feature = \"e2e\")]\nmod common;\n#[test] fn t() {}\n",
            ),
            (
                "tests/common/mod.rs",
                "#[cfg(feature = \"e2e\")] #[test] fn only_e2e() {}\n",
            ),
            (
                "tests/other.rs",
                "#[cfg(feature = \"e2e\")] #[test] fn other() {}\n",
            ),
        ]);
        assert_eq!(found.len(), 1, "{found:?}");
        assert!(
            found[0].starts_with("tests/other.rs:1: `other`"),
            "{found:?}"
        );
    }

    #[test]
    fn a_tree_with_no_tests_is_a_finding_not_a_pass() {
        let found = findings(&[("src/lib.rs", "fn not_a_test() {}\n")]);
        assert_eq!(found.len(), 1, "{found:?}");
        assert!(found[0].contains("saw no test"), "{found:?}");
    }

    #[test]
    fn a_shard_script_that_drops_either_selector_is_reported() {
        assert!(shard_filter_findings(SCRIPT).is_empty());
        let found = shard_filter_findings(
            "lane1='binary(/^e2e_/)'\nexec \"$@\" -E \"($lane1) & not $version\"\n",
        );
        assert_eq!(found.len(), 1, "{found:?}");
        assert!(found[0].contains("e2e_only"), "{found:?}");
        let none = shard_filter_findings("");
        assert_eq!(none.len(), 1, "{none:?}");
        assert!(none[0].contains("no `lane1=`"), "{none:?}");
    }

    #[test]
    fn a_parent_relative_path_module_is_checked() {
        let found = findings(&[
            ("src/lib.rs", PLAIN),
            (
                "src/shared.rs",
                "#[cfg(feature = \"e2e\")] #[test] fn shared() {}\n",
            ),
            (
                "tests/other.rs",
                "#[path = \"../src/shared.rs\"]\nmod shared;\n#[test] fn t() {}\n",
            ),
        ]);
        assert_eq!(found.len(), 1, "{found:?}");
        assert!(
            found[0].starts_with("src/shared.rs:1: `shared`"),
            "{found:?}"
        );
    }

    #[test]
    fn a_selector_left_only_in_a_comment_is_reported() {
        let script = "# binary(/^e2e_/) used to be here\n\
            lane1='(package(dot-agent-deck) & test(/(^|::)e2e_only[a-z0-9_]*::/))'\n\
            exec \"$@\" -E \"($lane1)\"\n";
        let found = shard_filter_findings(script);
        assert_eq!(found.len(), 1, "{found:?}");
        assert!(found[0].contains("binary(/^e2e_/)"), "{found:?}");
    }

    #[test]
    fn a_lane1_filter_nextest_is_not_given_is_reported() {
        let script = "lane1='binary(/^e2e_/) | (package(dot-agent-deck) & test(/(^|::)e2e_only[a-z0-9_]*::/))'\n\
            exec \"$@\" -E 'all()'\n";
        let found = shard_filter_findings(script);
        assert_eq!(found.len(), 1, "{found:?}");
        assert!(found[0].contains("no line passes"), "{found:?}");
    }
}
