/// The headline case. The store is read back into later prompts, so a row the
/// agent invents for an issue the run never touched is a durable, self-authored
/// instruction to itself. The prediction it *was* asked for is present and
/// correct; only the extra row is unaccounted for.
#[test]
fn issue_labeler_rejects_a_smuggled_prediction() {
    let fixture = MemoryFixture {
        memory: vec![(
            "predictions.jsonl",
            format!(
                "{}\n{}\n",
                prediction(42, &["bug", "priority:high", "size:low"]),
                prediction(9001, &["priority:low"]),
            ),
        )],
        baseline: vec![],
        agent_output: add_labels_output(&["bug", "priority:high", "size:low"]),
        event: opened_issue_event(42),
    };
    let Some(out) = fixture.run() else { return };
    assert!(
        out.rejected_with("changes do not match the triggering event"),
        "a row for an untouched issue was accepted:\n{}",
        out.stderr
    );
}

/// Same shape from the other side: the row is for *this* run's event but points
/// at another repository, which is how a poisoned store would reference content
/// the maintainers cannot see.
#[test]
fn issue_labeler_rejects_a_foreign_repository_url() {
    let fixture = MemoryFixture {
        memory: vec![(
            "predictions.jsonl",
            "{\"url\":\"https://github.com/attacker/evil/issues/42\",\"type\":\"issue\",\
             \"labels\":[\"bug\"]}\n"
                .to_string(),
        )],
        baseline: vec![],
        agent_output: add_labels_output(&["bug"]),
        event: opened_issue_event(42),
    };
    let Some(out) = fixture.run() else { return };
    assert!(
        out.rejected_with("invalid prediction entry"),
        "a prediction pointing outside {REPO_SLUG} was accepted:\n{}",
        out.stderr
    );
}

/// The taxonomy is enforced on the *memory* as well as on the labels applied.
/// `PRD` is on the safe-output blocklist, so it can never be applied — storing
/// it as a learned example would teach the model to keep proposing it.
#[test]
fn issue_labeler_rejects_a_non_taxonomy_label() {
    let fixture = MemoryFixture {
        memory: vec![(
            "predictions.jsonl",
            format!("{}\n", prediction(42, &["PRD"])),
        )],
        baseline: vec![],
        agent_output: add_labels_output(&["PRD"]),
        event: opened_issue_event(42),
    };
    let Some(out) = fixture.run() else { return };
    assert!(
        out.rejected_with("invalid labels"),
        "a blocked label was stored as a learned example:\n{}",
        out.stderr
    );
}

/// A prediction may name at most 6 labels. Paired with the seven-label feedback
/// test above, this is what holds the two caps apart in both directions.
#[test]
fn issue_labeler_rejects_an_oversized_prediction() {
    let seven = [
        "bug",
        "config",
        "daemon",
        "priority:high",
        "size:low",
        "source",
        "tests",
    ];
    let fixture = MemoryFixture {
        memory: vec![("predictions.jsonl", format!("{}\n", prediction(42, &seven)))],
        baseline: vec![],
        agent_output: add_labels_output(&seven),
        event: opened_issue_event(42),
    };
    let Some(out) = fixture.run() else { return };
    assert!(
        out.rejected_with("invalid labels"),
        "a 7-label prediction was accepted past the documented cap of 6:\n{}",
        out.stderr
    );
}

/// The memory clone is a git worktree the agent can write anywhere in. Only the
/// three `.jsonl` stores may exist in it, so an extra file — the natural shape
/// of an exfiltration or of a second, unvalidated store — fails the step.
#[test]
fn issue_labeler_rejects_an_unexpected_memory_file() {
    let fixture = MemoryFixture {
        memory: vec![
            (
                "predictions.jsonl",
                format!("{}\n", prediction(42, &["bug"])),
            ),
            ("notes.txt", "harvested\n".to_string()),
        ],
        baseline: vec![],
        agent_output: add_labels_output(&["bug"]),
        event: opened_issue_event(42),
    };
    let Some(out) = fixture.run() else { return };
    assert!(
        out.rejected_with("unexpected memory entry: notes.txt"),
        "an extra file in the memory clone was accepted:\n{}",
        out.stderr
    );
}

/// Feedback is only ground truth about a prediction the workflow actually made.
/// A correction recorded for an item it never classified is an unlabelled
/// example the model wrote for itself, so the validator requires the item to be
/// present in the pre-agent `predictions.jsonl`.
#[test]
fn issue_labeler_rejects_feedback_for_an_unclassified_item() {
    let fixture = MemoryFixture {
        memory: vec![(
            "feedback-issue.jsonl",
            format!("{}\n", feedback(42, &["bug"])),
        )],
        baseline: vec![],
        agent_output: NOOP_OUTPUT.to_string(),
        event: label_changed_event(42, "bug", &["bug"]),
    };
    let Some(out) = fixture.run() else { return };
    assert!(
        out.rejected_with("changes do not match the triggering event"),
        "feedback was stored for an item the workflow never classified:\n{}",
        out.stderr
    );
}

/// Feedback mode reacts to a human's label change, so it must never turn around
/// and apply labels of its own — that would let one maintainer edit trigger an
/// unbounded relabel, and each relabel is itself a `labeled` event.
#[test]
fn issue_labeler_rejects_labels_applied_in_feedback_mode() {
    let classified = format!("{}\n", prediction(42, &["bug"]));
    let fixture = MemoryFixture {
        memory: vec![("predictions.jsonl", classified.clone())],
        baseline: vec![("predictions.jsonl", classified)],
        agent_output: add_labels_output(&["priority:high"]),
        event: label_changed_event(42, "bug", &["bug"]),
    };
    let Some(out) = fixture.run() else { return };
    assert!(
        out.rejected_with("feedback mode must finish with noop"),
        "a feedback-mode run was allowed to apply labels:\n{}",
        out.stderr
    );
}
