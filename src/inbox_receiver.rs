//! PRD #1666: the inbox receiver the deck's agent integrations run, and the
//! placeholders every copy of the deck's inbox JavaScript is filled with.
//!
//! [`RECEIVER_JS`] (`src/inbox_receiver.js`) is one receiver on the deck's
//! receipt stream: it runs the `inbox wait --stream` watcher, holds the
//! attempts it is handed, sends possession snapshots and stage reports, asks
//! the final hand-over check and answers revokes and resumes. OpenCode's two
//! plugins inline it (`opencode_manage::inbox_js`). [`pi_module`] is an ES
//! module copy for the Pi extension, checked in at
//! `pi-extension/src/inbox-receiver.js` (with [`PI_MODULE_DTS`] beside it),
//! because Pi loads the extension's files as they are on disk and the deck
//! embeds them with `include_str!` (`orchestrator_ext::EXTENSION_FILES`); the
//! extension's `index.ts` imports it.
//! `inbox/pi/006` fails when the checked-in copy differs from the generator;
//! `DOT_AGENT_DECK_WRITE_PI_RECEIVER=1 cargo test-fast pi_006` rewrites it.

/// The receiver both integrations run, with its placeholders unfilled.
pub(crate) const RECEIVER_JS: &str = include_str!("inbox_receiver.js");

/// Where the Pi extension's generated copy of the receiver lives, relative
/// to the repository root, and its type declarations.
pub const PI_MODULE_PATH: &str = "pi-extension/src/inbox-receiver.js";
pub const PI_MODULE_DTS_PATH: &str = "pi-extension/src/inbox-receiver.d.ts";

/// `js` with the deck's values in place of its placeholders: the framing every
/// hand-over starts with ([`crate::inbox_hub::AGENT_FRAMING`]), the doorbell
/// line's two halves ([`crate::doorbell::LINE_PREFIX`],
/// [`crate::doorbell::LINE_SUFFIX`]), the adapter integration the watcher
/// declares and the keepalives before the deck retires a closed stream.
pub(crate) fn fill_placeholders(js: &str) -> String {
    let json = |text: &str| {
        serde_json::to_string(text).expect("serializing a &str to a String is infallible")
    };
    js.replace("__FRAMING_JSON__", &json(crate::inbox_hub::AGENT_FRAMING))
        .replace(
            "__DOORBELL_PREFIX_JSON__",
            &json(crate::doorbell::LINE_PREFIX.trim()),
        )
        .replace(
            "__DOORBELL_SUFFIX_JSON__",
            &json(crate::doorbell::LINE_SUFFIX),
        )
        .replace(
            "__ADAPTER_INTEGRATION__",
            &crate::inbox_hub::ADAPTER_INTEGRATION.to_string(),
        )
        .replace(
            "__RETIRE_KEEPALIVES__",
            &(crate::inbox_attempts::KEEPALIVES_PER_POSSESS_TTL
                * crate::inbox_attempts::CLOSED_RETIRE_TTLS)
                .to_string(),
        )
}

/// The Pi extension's copy of the receiver: an ES module around
/// [`RECEIVER_JS`], filled, that imports `spawn` and resolves the deck binary
/// through the function its importer passes to `inboxBinary`, running only
/// an absolute path to an executable file (`inbox/pi/031`).
pub fn pi_module() -> String {
    format!(
        "{PI_MODULE_HEAD}{}{PI_MODULE_TAIL}",
        fill_placeholders(RECEIVER_JS)
    )
}

const PI_MODULE_HEAD: &str = r#"// Generated by dot-agent-deck from src/inbox_receiver.js (PRD #1666). Do not
// edit: the fast test inbox/pi/006 fails when this file differs from its
// generator. Regenerate it with
// DOT_AGENT_DECK_WRITE_PI_RECEIVER=1 cargo test-fast pi_006
import { spawn } from "node:child_process";
import { accessSync, constants, statSync } from "node:fs";

// The deck binary the watcher runs, resolved at each spawn; `inboxBinary`
// sets how. Only an absolute path to an executable file is run. Anything
// else the resolver gives (nothing, a bare name the agent's PATH would look
// up, a path relative to its working directory, a missing or non-executable
// file) fails the spawn at once, so no watcher registers and nothing is
// handed over, and the receiver tries again on its backoff. A spawn Node
// fails later instead (a missing file) would report no exit, and the
// receiver would not try again.
let inboxBinaryOf = () => undefined;
const inboxAbsolute = (path) =>
  process.platform === "win32" ? /^([A-Za-z]:[\\/]|[\\/]{2})/.test(path) : path.startsWith("/");
const inboxRunnable = (path) => {
  if (typeof path !== "string" || !inboxAbsolute(path)) return false;
  try {
    if (!statSync(path).isFile()) return false;
    accessSync(path, constants.X_OK);
    return true;
  } catch (_) {
    return false;
  }
};
const hookBinary = () => {
  const path = inboxBinaryOf();
  return inboxRunnable(path) ? path : undefined;
};
"#;

const PI_MODULE_TAIL: &str = r#"// Sets how the receiver resolves the deck binary it runs its watcher with.
export const inboxBinary = (resolve) => {
  inboxBinaryOf = resolve;
};
export { INBOX_ADAPTER_INTEGRATION, inboxKey, inboxReceiver, inboxRef };
"#;

